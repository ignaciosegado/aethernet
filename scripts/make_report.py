"""Build figures + docs/RESULTS.md from docs/results/*.json (written by aethernet.sim.mc)."""
import json, pathlib, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

R = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "docs/results")
IMG = R.parent / "img"; IMG.mkdir(exist_ok=True)
NAMES = {"dead_reckoning": "IMU only (dead reckoning)", "v1_legacy": "v1 (original)", "v2": "v2 (this release)",
         "v2_naive_independent": "v2 ablation: peers treated independent", "v2_marginal_ci": "v2 ablation: marginal CI",
         "v2_frozen_bias": "v2 ablation: Schmidt frozen bias", "v2_no_altitude": "v2 ablation: 2-D ranges (no altitude)",
         "v2_no_latency_comp": "v2 ablation: no latency compensation"}
COL = {"dead_reckoning": "gray", "v1_legacy": "tab:red", "v2": "tab:green", "v2_naive_independent": "tab:orange",
       "v2_marginal_ci": "tab:purple", "v2_frozen_bias": "tab:brown", "v2_no_altitude": "tab:olive", "v2_no_latency_comp": "tab:cyan"}


def load(n):
    p = R / f"{n}.json"
    return json.loads(p.read_text()) if p.exists() else None


def pm(v, f="{:.2f}"):
    return (f + " ± " + f).format(*v)


def table(doc, cols):
    hdr = "| Algorithm | " + " | ".join(c[0] for c in cols) + " |\n|---|" + "---|" * len(cols) + "\n"
    rows = ""
    for a, r in doc["summary"].items():
        cells = []
        for _, key, fmt in cols:
            v = r[key]
            cells.append(pm(v, fmt) if isinstance(v, list) else fmt.format(v))
        rows += f"| {NAMES.get(a, a)} | " + " | ".join(cells) + " |\n"
    return hdr + rows


out = ["# Results (auto-generated by `scripts/make_report.py`)\n",
       "All numbers: mean ± 95 % CI over independent random scenarios (seeds 200+, never used for tuning; "
       "seeds 0-9 were the development set). 10 nodes, 120 s, tactical nodes 2-9 scored after a 10 s warm-up. "
       "Simulator deliberately differs from the filter's model (see `aethernet/sim/scenario.py`).\n"]

nom = load("nominal")
if nom:
    t = np.arange(len(next(iter(nom["series"].values()))["err_t"])) * nom["dt"]
    fig, ax = plt.subplots(1, 2, figsize=(13, 4.6))
    for a in ("dead_reckoning", "v1_legacy", "v2_naive_independent", "v2"):
        if a in nom["series"]:
            ax[0].plot(t, nom["series"][a]["err_t"], label=NAMES[a], color=COL[a], lw=2 if a == "v2" else 1.3)
            ax[1].plot(t, nom["series"][a]["nees_t"], label=NAMES[a], color=COL[a], lw=2 if a == "v2" else 1.3)
    ax[0].set_yscale("log"); ax[0].set_title("Mean position error, GNSS-denied nodes"); ax[0].set_xlabel("t (s)"); ax[0].set_ylabel("m"); ax[0].grid(alpha=.3, which="both"); ax[0].legend(fontsize=8)
    ax[1].set_yscale("log"); ax[1].axhline(2, color="k", ls="--", label="ideal NEES = 2"); ax[1].set_title("Consistency (NEES, 2 dof; ideal 2)"); ax[1].set_xlabel("t (s)"); ax[1].grid(alpha=.3, which="both"); ax[1].legend(fontsize=8)
    plt.tight_layout(); plt.savefig(IMG / "nominal.png", dpi=140); plt.close()
    out.append("## Nominal mission (anchor + relay with 40 s GNSS outage + 8 GNSS-denied nodes)\n")
    out.append(table(nom, [("RMSE (m)", "rmse", "{:.2f}"), ("p95 (m)", "p95", "{:.2f}"), ("max (m)", "max", "{:.1f}"),
                           ("relative RMSE (m)", "rel_rmse", "{:.2f}"), ("median NEES", "nees_median", "{:.2f}"),
                           ("% NEES > 13.8", "frac_nees_gt_99.9", "{:.1%}"), ("CPU s / run", "cpu_s", "{:.1f}")]))
    out.append("\n*Relative RMSE = pairwise inter-node distance error (what the swarm itself needs). "
               "% NEES > 13.8 should be ~0.1 % for a consistent filter.*\n\n![nominal](img/nominal.png)\n")

for name, title in (("spoof_jump", "GNSS jump spoof on the relay (+30 m at t = 40 s)"), ("spoof_drag", "GNSS drag spoof on the relay (0.4 m/s from t = 40 s)")):
    d = load(name)
    if not d:
        continue
    t = np.arange(len(d["series"]["v2"]["relay_err_t"])) * d["dt"]
    plt.figure(figsize=(7, 4))
    for a in d["series"]:
        plt.plot(t, d["series"][a]["relay_err_max_t"], color=COL[a], label=NAMES[a] + " (worst run)")
        plt.plot(t, d["series"][a]["relay_err_t"], color=COL[a], ls=":", label=NAMES[a] + " (mean)")
    plt.axvline(40, color="k", lw=.7); plt.yscale("log"); plt.title(title); plt.xlabel("t (s)"); plt.ylabel("relay position error (m)"); plt.grid(alpha=.3, which="both"); plt.legend(fontsize=7)
    plt.tight_layout(); plt.savefig(IMG / f"{name}.png", dpi=140); plt.close()
    out.append(f"## {title}\n")
    out.append(table(d, [("relay RMSE (m)", "relay_rmse", "{:.2f}"), ("relay max err (m)", "relay_max", "{:.1f}"),
                         ("tactical RMSE (m)", "rmse", "{:.2f}"), ("tactical max (m)", "max", "{:.1f}")]))
    out.append(f"\n![{name}](img/{name}.png)\n")

for name, title in (("imu_stall", "3 s IMU stall on nodes 3-5 at t = 60 s"), ("anchorless", "No fixed anchor; relay GNSS only for the first 40 s")):
    d = load(name)
    if not d:
        continue
    out.append(f"## {title}\n")
    out.append(table(d, [("RMSE (m)", "rmse", "{:.2f}"), ("p95 (m)", "p95", "{:.2f}"), ("max (m)", "max", "{:.1f}"),
                         ("relative RMSE (m)", "rel_rmse", "{:.2f}"), ("median NEES", "nees_median", "{:.2f}"),
                         ("% NEES > 13.8", "frac_nees_gt_99.9", "{:.1%}")]))
    out.append("")

(R.parent / "RESULTS.md").write_text("\n".join(out))
print("wrote", R.parent / "RESULTS.md")
